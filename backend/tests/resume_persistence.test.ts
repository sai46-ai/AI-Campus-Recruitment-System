import request from 'supertest';
import app from '../src/app';
import path from 'path';
import fs from 'fs';
import mongoose from 'mongoose';
import { generateAccessToken } from '../src/shared/utils/jwt';
import { UserRole } from '../src/shared/constants/roles';
import { getUploadDir, getResumeUploadDir } from '../src/shared/middleware/upload';
import * as geminiService from '../src/shared/services/geminiService';
import * as fileParser from '../src/shared/utils/fileParser';
import Resume from '../src/features/resumes/resumeModel';
import User from '../src/features/auth/userModel';
import Application from '../src/features/applications/applicationModel';
import Job from '../src/features/jobs/jobModel';

/**
 * Phase 01: Resume Persistence & Access Control Test Suite
 *
 * Validates:
 * 1. Storage directory resolution & UPLOAD_DIR env configuration
 * 2. Synthetic resume upload and persistent file storage on disk
 * 3. Authorized download matching uploaded file byte-for-byte
 * 4. Authentication enforcement (401 on unauthenticated access)
 * 5. Strict cross-user isolation (403 when User B accesses User A's file)
 * 6. Recruiter context boundary (403 without active application context)
 * 7. Authorized administrative access (200 for Admin audit)
 * 8. Physical file removal upon resume deletion
 */

describe('Phase 01 - Resume Storage Persistence & Access Control', () => {
  const studentAId = '65432177bcf86cd799439001';
  const studentBId = '65432177bcf86cd799439002';
  const recruiterId = '65432177bcf86cd799439003';
  const adminId = '65432177bcf86cd799439004';
  const testResumeObjectId = new mongoose.Types.ObjectId('65432177bcf86cd799439099');

  const studentAToken = generateAccessToken({ userId: studentAId, role: UserRole.STUDENT, email: 'studentA@campus.edu' });
  const studentBToken = generateAccessToken({ userId: studentBId, role: UserRole.STUDENT, email: 'studentB@campus.edu' });
  const recruiterToken = generateAccessToken({ userId: recruiterId, role: UserRole.RECRUITER, email: 'recruiter@tech.com' });
  const adminToken = generateAccessToken({ userId: adminId, role: UserRole.ADMIN, email: 'admin@campus.edu' });

  // Synthetic resume payload (strictly synthetic - never real PII)
  const syntheticContent = 'SYNTHETIC_TEST_RESUME_CONTENT_FOR_PHASE_01_PERSISTENCE_VERIFICATION';
  let createdFileName = '';
  let createdFilePath = '';
  let mockResumeDoc: any = null;

  afterEach(() => {
    jest.restoreAllMocks();
  });

  afterAll(() => {
    // Cleanup any lingering synthetic test file on disk
    if (createdFilePath && fs.existsSync(createdFilePath)) {
      try {
        fs.unlinkSync(createdFilePath);
      } catch {}
    }
  });

  describe('1. Storage Path Architecture & Environment Overrides', () => {
    it('should resolve default upload path under process.cwd()/uploads/resumes', () => {
      const baseDir = getUploadDir();
      const resumeDir = getResumeUploadDir();
      expect(baseDir).toBe(path.join(process.cwd(), 'uploads'));
      expect(resumeDir).toBe(path.join(process.cwd(), 'uploads', 'resumes'));
    });

    it('should respect custom UPLOAD_DIR environment variable when set', () => {
      const originalEnv = process.env.UPLOAD_DIR;
      try {
        process.env.UPLOAD_DIR = path.resolve('test_persistent_storage');
        expect(getUploadDir()).toBe(path.resolve('test_persistent_storage'));
        expect(getResumeUploadDir()).toBe(path.resolve('test_persistent_storage', 'resumes'));
      } finally {
        if (originalEnv !== undefined) {
          process.env.UPLOAD_DIR = originalEnv;
        } else {
          delete process.env.UPLOAD_DIR;
        }
      }
    });
  });

  describe('2. Synthetic Resume Upload & Persistent File Storage', () => {
    it('should upload synthetic resume, store physical file in uploads directory, and record in DB', async () => {
      // Mock User and external AI parser
      jest.spyOn(User, 'findByIdAndUpdate').mockResolvedValue({} as any);
      jest.spyOn(fileParser, 'extractTextFromFile').mockResolvedValue(syntheticContent);
      jest.spyOn(geminiService, 'parseResumeWithGemini').mockResolvedValue({
        name: 'Synthetic Student A',
        email: 'studentA@campus.edu',
        phone: '1234567890',
        summary: 'Synthetic summary for testing',
        skills: ['TypeScript', 'Node.js', 'Docker'],
        experience: [],
        education: [],
        projects: [],
        certifications: [],
        atsScore: 85,
        atsBreakdown: { skillCoverageScore: 25, experienceScore: 20, educationScore: 20, formattingScore: 20 },
        aiSuggestions: ['Add more metrics'],
      });

      // Mock Resume.findOne returning null (first-time upload)
      jest.spyOn(Resume, 'findOne').mockResolvedValue(null);

      // Mock Resume.create capturing the fileUrl generated by Multer
      jest.spyOn(Resume, 'create').mockImplementation(async (data: any) => {
        createdFileName = path.basename(data.fileUrl);
        createdFilePath = path.join(getResumeUploadDir(), createdFileName);

        mockResumeDoc = {
          _id: testResumeObjectId,
          id: testResumeObjectId.toString(),
          student: new mongoose.Types.ObjectId(studentAId),
          fileUrl: data.fileUrl,
          originalName: data.originalName,
          mimeType: data.mimeType,
          size: data.size,
          rawText: data.rawText,
          parsedData: data.parsedData,
          personalInfo: { name: 'Synthetic Student A' },
          skills: { 'Technical Skills': ['TypeScript', 'Node.js', 'Docker'] },
          atsScore: 85,
          versionHistory: [],
          toObject: function () {
            return {
              _id: this._id,
              id: this._id.toString(),
              student: this.student,
              fileUrl: this.fileUrl,
              originalName: this.originalName,
              mimeType: this.mimeType,
              size: this.size,
              rawText: this.rawText,
              parsedData: this.parsedData,
              personalInfo: this.personalInfo,
              skills: this.skills,
              atsScore: this.atsScore,
            };
          },
        };
        return mockResumeDoc as any;
      });

      const res = await request(app)
        .post('/api/v1/resumes/upload')
        .set('Authorization', `Bearer ${studentAToken}`)
        .attach('resume', Buffer.from(syntheticContent, 'utf-8'), {
          filename: 'synthetic_student_a_resume.txt',
          contentType: 'text/plain',
        });

      expect(res.status).toBe(200);
      expect(res.body.success).toBe(true);
      expect(res.body.data).toBeDefined();

      // Verify physical file was written by Multer to persistent storage on disk
      expect(createdFilePath).toBeDefined();
      expect(fs.existsSync(createdFilePath)).toBe(true);

      // Verify file content on disk matches uploaded synthetic content byte-for-byte
      const diskContent = fs.readFileSync(createdFilePath, 'utf-8');
      expect(diskContent).toBe(syntheticContent);
    });
  });

  describe('3. Authorized Download & Byte-for-Byte Retrieval', () => {
    it('should allow student owner to download their uploaded resume with exact content', async () => {
      jest.spyOn(Resume, 'findById').mockResolvedValue(mockResumeDoc);

      const res = await request(app)
        .get(`/api/v1/resumes/${testResumeObjectId.toString()}/download`)
        .set('Authorization', `Bearer ${studentAToken}`);

      expect(res.status).toBe(200);
      expect(res.headers['content-disposition']).toContain('attachment');
      expect(res.headers['content-disposition']).toContain('synthetic_student_a_resume.txt');
      expect(res.text).toBe(syntheticContent);
    });

    it('should allow Admin to download student resume for audit/compliance', async () => {
      jest.spyOn(Resume, 'findById').mockResolvedValue(mockResumeDoc);

      const res = await request(app)
        .get(`/api/v1/resumes/${testResumeObjectId.toString()}/download`)
        .set('Authorization', `Bearer ${adminToken}`);

      expect(res.status).toBe(200);
      expect(res.text).toBe(syntheticContent);
    });
  });

  describe('4. Security & Access Control Boundaries (Data Safety)', () => {
    it('should reject unauthenticated download requests with 401', async () => {
      const res = await request(app)
        .get(`/api/v1/resumes/${testResumeObjectId.toString()}/download`);

      expect(res.status).toBe(401);
    });

    it('should reject cross-user access: Student B cannot download Student A resume (403)', async () => {
      jest.spyOn(Resume, 'findById').mockResolvedValue(mockResumeDoc);

      const res = await request(app)
        .get(`/api/v1/resumes/${testResumeObjectId.toString()}/download`)
        .set('Authorization', `Bearer ${studentBToken}`);

      expect(res.status).toBe(403);
      expect(res.body.message).toMatch(/unauthorized/i);
    });

    it('should reject Recruiter download without active application context (403)', async () => {
      jest.spyOn(Resume, 'findById').mockResolvedValue(mockResumeDoc);

      const res = await request(app)
        .get(`/api/v1/resumes/${testResumeObjectId.toString()}/download`)
        .set('Authorization', `Bearer ${recruiterToken}`);

      expect(res.status).toBe(403);
      expect(res.body.message).toMatch(/application context is required/i);
    });

    it('should reject Recruiter download if application belongs to another recruiter (403)', async () => {
      const fakeAppId = '507f1f77bcf86cd799439099';
      const otherRecruiterJobId = '507f1f77bcf86cd799439088';

      jest.spyOn(Resume, 'findById').mockResolvedValue(mockResumeDoc);
      jest.spyOn(Application, 'findOne').mockReturnValue({
        select: jest.fn().mockResolvedValue({ _id: fakeAppId, job: otherRecruiterJobId }),
      } as any);
      jest.spyOn(Job, 'exists').mockResolvedValue(null); // Recruiter does not own this job

      const res = await request(app)
        .get(`/api/v1/resumes/${testResumeObjectId.toString()}/download?applicationId=${fakeAppId}`)
        .set('Authorization', `Bearer ${recruiterToken}`);

      expect(res.status).toBe(403);
      expect(res.body.message).toMatch(/unauthorized/i);
    });
  });

  describe('5. Persistence Retention & Safe Deletion Lifecycle', () => {
    it('should confirm file persists on disk independently of process memory', () => {
      expect(fs.existsSync(createdFilePath)).toBe(true);
      const reRead = fs.readFileSync(createdFilePath, 'utf-8');
      expect(reRead).toBe(syntheticContent);
    });

    it('should remove physical file when resume is deleted by its owner', async () => {
      jest.spyOn(Resume, 'findOneAndDelete').mockResolvedValue(mockResumeDoc);

      const res = await request(app)
        .delete(`/api/v1/resumes/${testResumeObjectId.toString()}`)
        .set('Authorization', `Bearer ${studentAToken}`);

      expect(res.status).toBe(200);
      expect(res.body.success).toBe(true);

      // Give file deletion a brief tick to finish
      await new Promise((resolve) => setTimeout(resolve, 80));
      expect(fs.existsSync(createdFilePath)).toBe(false);
    });
  });
});
